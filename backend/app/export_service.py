import io
import base64
from datetime import datetime
from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment
from openpyxl.utils import get_column_letter

def generate_pdf_report(form_data: dict, tax_data: dict, chart_image: str | None = None) -> io.BytesIO:
    """Generates an executive PDF tax comparison dossier."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, rightMargin=54, leftMargin=54, topMargin=54, bottomMargin=36)
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle('Title', parent=styles['Heading1'], fontSize=22, alignment=TA_CENTER, textColor=colors.HexColor("#4F46E5"), spaceAfter=15)
    footer_style = ParagraphStyle('Footer', parent=styles['Normal'], fontSize=9, alignment=TA_CENTER, textColor=colors.grey)

    story = [
        Paragraph("TAXYNC Tax Analysis & Planning Dossier", title_style),
        Paragraph(f"Financial Year 2025-26 | Generated on {datetime.now().strftime('%d %B %Y')}", footer_style),
        Spacer(1, 15),
    ]

    # Comparison Table
    table_data = [
        ['Parameter', 'Old Regime', 'New Regime'],
        ['Gross Annual Income', f"₹{form_data.get('income', 0):,}", f"₹{form_data.get('income', 0):,}"],
        ['Estimated Tax', f"₹{tax_data.get('old_regime_tax', 0):,}", f"₹{tax_data.get('new_regime_tax', 0):,}"],
        ['Recommended Advantage', tax_data.get('regime_comparison', f"Savings: ₹{tax_data.get('savings', 0):,}"), '']
    ]
    t = Table(table_data, colWidths=[2.5 * inch, 2.2 * inch, 2.2 * inch])
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#4F46E5")),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.lightgrey),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.whitesmoke]),
    ]))
    story.extend([t, Spacer(1, 20)])

    # Embed Chart Image
    if chart_image and "," in chart_image:
        try:
            _, encoded = chart_image.split(",", 1)
            img_buf = io.BytesIO(base64.b64decode(encoded))
            img = Image(img_buf, width=5 * inch, height=3 * inch)
            img.hAlign = 'CENTER'
            story.extend([img, Spacer(1, 15)])
        except Exception:
            pass

    # Suggestions
    suggestions = tax_data.get('optimization_suggestions') or tax_data.get('suggestions', [])
    if suggestions:
        story.append(Paragraph("<b>Optimization Recommendations:</b>", styles['Heading3']))
        for s in suggestions[:5]:
            story.append(Paragraph(f"• {s}", styles['Normal']))
            story.append(Spacer(1, 4))
        story.append(Spacer(1, 15))

    story.append(Paragraph("Generated by Taxync | Personal Tax Planning Engine", footer_style))
    doc.build(story)
    buffer.seek(0)
    return buffer

def generate_excel_report(form_data: dict, tax_data: dict) -> io.BytesIO:
    """Generates a structured Excel tax workbook."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Tax Comparison"

    # Header
    ws.merge_cells('A1:C1')
    ws['A1'] = 'TAXYNC - Tax Analysis Report (FY 2025-26)'
    ws['A1'].font = Font(name='Arial', size=16, bold=True, color='4F46E5')
    ws['A1'].alignment = Alignment(horizontal='center')

    headers = ['Category', 'Old Regime (₹)', 'New Regime (₹)']
    for col, h in enumerate(headers, 1):
        cell = ws.cell(row=3, column=col, value=h)
        cell.font = Font(bold=True, color='FFFFFF')
        cell.fill = PatternFill(start_color='4F46E5', end_color='4F46E5', fill_type='solid')

    rows = [
        ['Gross Income', form_data.get('income', 0), form_data.get('income', 0)],
        ['Standard Deduction', form_data.get('standardDeduction', 50000), 75000],
        ['Section 80C', form_data.get('section80C', 0), 0],
        ['Section 80D', form_data.get('section80D', 0), 0],
        ['HRA', form_data.get('hra', 0), 0],
        ['Final Tax Payable', tax_data.get('old_regime_tax', 0), tax_data.get('new_regime_tax', 0)],
        ['Net Savings', tax_data.get('savings', 0), 0],
    ]

    for r_idx, row in enumerate(rows, 4):
        ws.cell(row=r_idx, column=1, value=row[0])
        for c_idx in (2, 3):
            c = ws.cell(row=r_idx, column=c_idx, value=row[c_idx - 1])
            c.number_format = '₹#,##0'

    # Column width formatting
    for col_idx in range(1, 4):
        ws.column_dimensions[get_column_letter(col_idx)].width = 24

    buf = io.BytesIO()
    wb.save(buf)
    buf.seek(0)
    return buf
